def manifest_case(name, m):
    c = canonical(m)
    sig = Account.sign_message(encode_defunct(primitive=c.encode()), DEV_KEY).signature.hex()
    if not sig.startswith("0x"):
        sig = "0x" + sig
    return {
        "name": name, "manifest": m, "canonical": c, "canonical_hex": "0x" + c.encode().hex(),
        "manifest_hash": h(c.encode()), "consensus_hash": h(canonical(m["consensus"]).encode()),
        "project_id": project_id(m["developer"], m["slug"]), "signature": sig, "signer": DEV,
    }


