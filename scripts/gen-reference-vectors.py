import json
from eth_hash.auto import keccak
from eth_abi import encode as abi_encode
from eth_account import Account
from eth_account.messages import encode_defunct

DEV_KEY = "0x" + "00" * 31 + "01"
OWNER_KEY = "0x" + "00" * 31 + "02"
DEV = Account.from_key(DEV_KEY).address.lower()
OWNER = Account.from_key(OWNER_KEY).address.lower()


def canonical(o):
    return json.dumps(o, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def h(b):
    return "0x" + keccak(b).hex()


def project_id(dev, slug):
    return h(b"necter-project-v1:" + bytes.fromhex(dev[2:]) + slug.encode())


def vault(factory, impl, pid):
    init = bytes.fromhex("3d602d80600a3d3981f3363d3d373d3d3d363d73" + impl[2:] + "5af43d82803e903d91602b57fd5bf3")
    raw = keccak(b"\xff" + bytes.fromhex(factory[2:]) + bytes.fromhex(pid[2:]) + keccak(init))
    return "0x" + raw[12:].hex()


